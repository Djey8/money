'use strict';

/**
 * Subscriptions (SUB-1..4) are `{tag-less title, account, amountMinor,
 * startDate, endDate, category, comment, frequency}` recurring-transaction
 * templates. `changeHistory`/`SubscriptionChange` exists on the original
 * `Subscription` interface but is confirmed dead — `add-subscription.component.ts`
 * initializes it to `[]` and nothing anywhere ever pushes to it, on create or
 * edit — so it isn't carried into this API.
 *
 * **`PATCH` keeps the subscription's generated transactions in line with it**
 * (JFK, 2026-10-10), by one rule (`staleGeneratedTransactions`,
 * packages/domain/src/transactions/subscription-sync.ts): what the OLD
 * subscription generated and the NEW one would not generate is removed - all
 * of it when the details (title, comment, account, amount, category) change,
 * the occurrences after the new end date when only the end date moves into the
 * past - and then whatever the new subscription is due and lacks is generated
 * (`generateDueSubscriptionTransactions`, as `refresh` does): all of it after a
 * details change, the missing ones when the end date moves into the future.
 * A transaction is recognised as generated by its account, amount, category,
 * comment (plus any fund tags) AND a date that was one of the subscription's
 * occurrences, so a hand-made transaction that merely looks alike stays. (The
 * original app matched on account+amount+category alone and never
 * regenerated; an end date change did nothing.)
 *
 * **`DELETE` takes an explicit `deleteTransactions` option** instead of a UI
 * checkbox's implicit state (`InfoSubscriptionComponent.isRefresh`) — same
 * optional behavior, just an explicit parameter, with the same recognition rule.
 *
 * Any transaction-list change here runs through the same `applyDerivedState`
 * recompute every other transaction write goes through, so deleting
 * subscription-generated transactions correctly unwinds their effect on
 * Mojo/Smile/Fire fund state and the Income accounting rebuild.
 */

const crypto = require('crypto');
const {
  toMinorUnits,
  transactionFromApi,
  generateDueSubscriptionTransactions,
  staleGeneratedTransactions,
  reconcileGeneratedTransactions,
  validateLocationSplitRule,
} = require('@money/domain');
const { getEncryptionSession } = require('../services/encryption-session');
const { assertNotPlanOwned } = require('../services/payment-plan-links');
const {
  decryptValue,
  toApiTransactions,
  encryptTransaction,
  readLocationIds,
  locationNotFoundError,
  locationSplitError,
} = require('./transaction-repository');
const {
  writeValue,
  toStoredMoney,
  applyDerivedState,
  buildDerivedStateContext,
} = require('../services/transaction-derived-state');

const MAX_WRITE_RETRIES = 10;

function decryptMoney(value, session, schemaVersion) {
  const numeric = Number(decryptValue(value, session));
  return schemaVersion >= 2 ? numeric : toMinorUnits(numeric);
}

function decryptEndDate(raw, session) {
  if (raw === undefined) return null;
  const value = decryptValue(raw, session);
  return value === '' ? null : value;
}

function decryptSubscription(raw, session, schemaVersion) {
  return {
    id: decryptValue(raw.id, session),
    title: decryptValue(raw.title, session),
    account: decryptValue(raw.account, session),
    amountMinor: decryptMoney(raw.amount, session, schemaVersion),
    startDate: decryptValue(raw.startDate, session),
    endDate: decryptEndDate(raw.endDate, session),
    category: decryptValue(raw.category, session),
    comment: raw.comment !== undefined ? decryptValue(raw.comment, session) : '',
    frequency: decryptValue(raw.frequency, session),
    // Where the generated bookings land. Absent (never null) when the subscription has none.
    ...(raw.locationId !== undefined ? { locationId: decryptValue(raw.locationId, session) } : {}),
    ...(Array.isArray(raw.locationSplit) && raw.locationSplit.length > 0
      ? { locationSplit: decryptSplitRule(raw.locationSplit, session, schemaVersion) }
      : {}),
  };
}

/** The other-location rule: stored as {locationId, percent | amount} with each value encrypted on its own. */
function decryptSplitRule(rule, session, schemaVersion) {
  return rule.map((leg) => ({
    locationId: decryptValue(leg.locationId, session),
    ...(leg.percent !== undefined ? { percent: Number(decryptValue(leg.percent, session)) } : {}),
    ...(leg.amount !== undefined
      ? { amountMinor: decryptMoney(leg.amount, session, schemaVersion) }
      : {}),
  }));
}

function encryptSplitRule(rule, session, schemaVersion) {
  return rule.map((leg) => ({
    locationId: writeValue(leg.locationId, session),
    ...(leg.percent !== undefined ? { percent: writeValue(leg.percent, session) } : {}),
    ...(leg.amountMinor !== undefined
      ? { amount: writeValue(toStoredMoney(leg.amountMinor, schemaVersion), session) }
      : {}),
  }));
}

function encryptSubscription(subscription, session, schemaVersion) {
  return {
    id: writeValue(subscription.id, session),
    title: writeValue(subscription.title, session),
    account: writeValue(subscription.account, session),
    amount: writeValue(toStoredMoney(subscription.amountMinor, schemaVersion), session),
    startDate: writeValue(subscription.startDate, session),
    endDate: writeValue(subscription.endDate || '', session),
    category: writeValue(subscription.category, session),
    comment: writeValue(subscription.comment || '', session),
    frequency: writeValue(subscription.frequency, session),
    ...(subscription.locationId
      ? { locationId: writeValue(subscription.locationId, session) }
      : {}),
    ...(Array.isArray(subscription.locationSplit) && subscription.locationSplit.length > 0
      ? { locationSplit: encryptSplitRule(subscription.locationSplit, session, schemaVersion) }
      : {}),
  };
}

/** A subscription may only be pointed at one of the caller's existing locations (an unchanged stale link is tolerated). */
function assertLocationKnown(data, session, locationId, currentLocationId) {
  if (!locationId || locationId === currentLocationId) return;
  if (!readLocationIds(data, session).has(locationId)) throw locationNotFoundError(locationId);
}

/**
 * The rule for the OTHER locations (a percentage or a fixed amount each; the main location gets the rest).
 * Empty means none and is removed from the subscription; a non-empty rule needs a main `locationId`, sound
 * numbers, and locations that exist (a leg that was already there and has since vanished is tolerated).
 */
function normalizeSplitRule(subscription, data, session, previousRule) {
  const rule = subscription.locationSplit;
  if (!Array.isArray(rule) || rule.length === 0) {
    delete subscription.locationSplit;
    return;
  }
  const message = validateLocationSplitRule(rule, subscription.locationId);
  if (message) throw locationSplitError(message);
  const known = readLocationIds(data, session);
  const previous = new Set((previousRule ?? []).map((leg) => leg.locationId));
  for (const leg of rule) {
    if (!known.has(leg.locationId) && !previous.has(leg.locationId)) {
      throw locationNotFoundError(leg.locationId);
    }
  }
}

function assertStableId(rawSubscription) {
  if (rawSubscription.id === undefined) {
    throw new Error(
      'Subscription is missing a stable ID; run mm-admin migrate-balance-entity-ids --collection subscriptions first',
    );
  }
}

async function loadUserData({ usersDb, authDb }, userId) {
  let userDoc;
  try {
    userDoc = await usersDb.get(userId);
  } catch (error) {
    if (error.statusCode !== 404) throw error;
    userDoc = { data: {} };
  }
  const data = userDoc.data || {};
  const session = await getEncryptionSession(authDb, userId);
  const schemaVersion = data.meta?.schemaVersion || 1;
  return { userDoc, data, session, schemaVersion };
}

function decryptAllSubscriptions(rawSubscriptions, session, schemaVersion) {
  return rawSubscriptions.map((raw) => {
    assertStableId(raw);
    return decryptSubscription(raw, session, schemaVersion);
  });
}

async function listSubscriptions(deps, userId) {
  const { data, session, schemaVersion } = await loadUserData(deps, userId);
  const rawSubscriptions = data.subscriptions || [];
  if (!Array.isArray(rawSubscriptions)) throw new Error('Stored subscriptions must be an array');
  return decryptAllSubscriptions(rawSubscriptions, session, schemaVersion);
}

async function getSubscription(deps, userId, subscriptionId) {
  const subscriptions = await listSubscriptions(deps, userId);
  return subscriptions.find((subscription) => subscription.id === subscriptionId) || null;
}

/** Matches `transactionExistsForDate`'s 4 identifying fields (everything but `date`) — see this file's header comment for why it's a tighter match than the original's own PATCH-time cleanup. */
function buildConstructedComment(title, comment) {
  return comment ? `${title} + ${comment}` : title;
}

/**
 * The transactions after `before` became `after`: the ones the new subscription still has an occurrence for are changed in
 * place (same id, same place in the list), the ones it has none for are dropped.
 */
function reconciledTransactions(before, after, existingTransactions, now) {
  const { updates, removals } = reconcileGeneratedTransactions(
    before,
    after,
    existingTransactions,
    now,
  );
  const updateOf = new Map(updates.map((update) => [update.index, update]));
  const removed = new Set(removals);
  return existingTransactions.flatMap((transaction, index) => {
    if (removed.has(index)) return [];
    const update = updateOf.get(index);
    if (!update) return [transaction];
    const { index: _index, ...changes } = update;
    return [{ ...transaction, ...changes }];
  });
}

/** The transactions that stay when `before` becomes `after` (`null`: it is deleted). */
function withoutStaleGenerated(before, after, existingTransactions, now) {
  const stale = new Set(staleGeneratedTransactions(before, after, existingTransactions, now));
  return existingTransactions.filter((_, index) => !stale.has(index));
}

/**
 * Shared read → mutate → write-with-retry-on-409 loop. `mutate` receives the
 * still-encrypted `rawSubscriptions` plus the full `data` document (needed
 * to reach `data.transactions` for the PATCH/DELETE cascade) and returns one
 * of:
 * - `null` — nothing to do (e.g. the target id doesn't exist); no write happens.
 * - `{ skipWrite: true, result }` — a no-op outcome (e.g. a refresh that had
 *   nothing due); no write happens, `result` is returned as-is.
 * - `{ updatedData, result }` — the new full data document to persist.
 *   `mutate` builds `updatedData` itself (rather than this loop assembling it
 *   from named parts) since a cascade needs to overlay
 *   `subscriptions`/`transactions` on top of `applyDerivedState`'s own full
 *   data patch, not just `data`.
 */
async function withSubscriptionsWrite({ usersDb, authDb }, userId, mutate) {
  let attempt = 0;
  while (attempt < MAX_WRITE_RETRIES) {
    let userDoc;
    try {
      userDoc = await usersDb.get(userId);
    } catch (error) {
      if (error.statusCode !== 404) throw error;
      userDoc = {
        _id: userId,
        createdAt: new Date().toISOString(),
        updatedAt: new Date().toISOString(),
        data: {},
      };
    }
    const data = userDoc.data || {};
    const session = await getEncryptionSession(authDb, userId);
    const schemaVersion = data.meta?.schemaVersion || 1;
    const currency = data.meta?.currency || 'EUR';
    const rawSubscriptions = data.subscriptions || [];
    if (!Array.isArray(rawSubscriptions)) throw new Error('Stored subscriptions must be an array');

    const mutation = mutate({ data, rawSubscriptions, session, schemaVersion, currency });
    if (mutation === null) return null;
    if (mutation.skipWrite) return mutation.result;
    const { updatedData, result } = mutation;
    const now = new Date().toISOString();
    try {
      await usersDb.insert({ ...userDoc, data: updatedData, updatedAt: now });
      return result;
    } catch (error) {
      if (error.statusCode !== 409) throw error;
      attempt += 1;
    }
  }
  throw new Error('Failed to write subscriptions after maximum retries due to write conflicts');
}

async function createSubscription(deps, userId, input) {
  return withSubscriptionsWrite(
    deps,
    userId,
    ({ data, rawSubscriptions, session, schemaVersion }) => {
      assertLocationKnown(data, session, input.locationId);
      const newSubscription = {
        id: `subscriptions_${crypto.randomUUID()}`,
        title: input.title || '',
        account: input.account,
        amountMinor: input.amountMinor,
        startDate: input.startDate,
        endDate: input.endDate || null,
        category: input.category,
        comment: input.comment || '',
        frequency: input.frequency || 'monthly',
        ...(input.locationId ? { locationId: input.locationId } : {}),
        ...(Array.isArray(input.locationSplit) ? { locationSplit: input.locationSplit } : {}),
      };
      normalizeSplitRule(newSubscription, data, session);
      return {
        updatedData: {
          ...data,
          subscriptions: [
            ...rawSubscriptions,
            encryptSubscription(newSubscription, session, schemaVersion),
          ],
        },
        result: newSubscription,
      };
    },
  );
}

async function updateSubscription(deps, userId, subscriptionId, patch, { now = new Date() } = {}) {
  return withSubscriptionsWrite(
    deps,
    userId,
    ({ data, rawSubscriptions, session, schemaVersion, currency }) => {
      const existing = decryptAllSubscriptions(rawSubscriptions, session, schemaVersion);
      const index = existing.findIndex((subscription) => subscription.id === subscriptionId);
      if (index === -1) return null;
      assertNotPlanOwned(data, rawSubscriptions[index], session);
      const current = existing[index];
      assertLocationKnown(data, session, patch.locationId, current.locationId);
      const { locationId: patchedLocation, ...otherPatch } = patch;
      const updated = { ...current, ...otherPatch };
      if (patchedLocation !== undefined) {
        // null clears it; the stored subscription never carries a null.
        if (patchedLocation) updated.locationId = patchedLocation;
        else delete updated.locationId;
      }
      // Without a main location there is nothing to split from: clearing it clears an old rule too.
      if (!updated.locationId && patch.locationSplit === undefined) delete updated.locationSplit;
      normalizeSplitRule(updated, data, session, current.locationSplit);

      const updatedRawSubscriptions = rawSubscriptions.map((raw, i) =>
        i === index ? encryptSubscription(updated, session, schemaVersion) : raw,
      );

      const rawTransactions = data.transactions || [];
      const existingTransactions = toApiTransactions(
        rawTransactions,
        session,
        schemaVersion,
        currency,
      );
      const remainingTransactions = reconciledTransactions(
        current,
        updated,
        existingTransactions,
        now,
      );
      const fundState = buildDerivedStateContext(data, session, schemaVersion).funds;
      const generation = generateDueSubscriptionTransactions(
        [updated],
        remainingTransactions,
        fundState,
        now,
      );
      const changed =
        remainingTransactions.length !== existingTransactions.length ||
        remainingTransactions.some((transaction, i) => transaction !== existingTransactions[i]);
      if (!changed && generation.transactionsCreated === 0) {
        return {
          updatedData: { ...data, subscriptions: updatedRawSubscriptions },
          result: updated,
        };
      }

      const newTransactions = generation.transactions.map((transaction) => ({
        ...transaction,
        id: `tx_${crypto.randomUUID()}`,
        currency,
      }));
      const derived = applyDerivedState(
        data,
        [...remainingTransactions, ...newTransactions],
        session,
        schemaVersion,
        existingTransactions,
      );
      const updatedRawTransactions = derived.transactions.map((effective) =>
        encryptTransaction(transactionFromApi(effective, schemaVersion), session),
      );
      return {
        updatedData: {
          ...derived.data,
          subscriptions: updatedRawSubscriptions,
          transactions: updatedRawTransactions,
        },
        result: updated,
      };
    },
  );
}

async function deleteSubscription(
  deps,
  userId,
  subscriptionId,
  { deleteTransactions = false, now = new Date() } = {},
) {
  return withSubscriptionsWrite(
    deps,
    userId,
    ({ data, rawSubscriptions, session, schemaVersion, currency }) => {
      const existing = decryptAllSubscriptions(rawSubscriptions, session, schemaVersion);
      const index = existing.findIndex((subscription) => subscription.id === subscriptionId);
      if (index === -1) return null;
      assertNotPlanOwned(data, rawSubscriptions[index], session);
      const current = existing[index];
      const updatedRawSubscriptions = rawSubscriptions.filter((_, i) => i !== index);

      if (!deleteTransactions) {
        return {
          updatedData: { ...data, subscriptions: updatedRawSubscriptions },
          result: { id: subscriptionId },
        };
      }

      const rawTransactions = data.transactions || [];
      const existingTransactions = toApiTransactions(
        rawTransactions,
        session,
        schemaVersion,
        currency,
      );
      const remainingTransactions = withoutStaleGenerated(current, null, existingTransactions, now);
      if (remainingTransactions.length === existingTransactions.length) {
        return {
          updatedData: { ...data, subscriptions: updatedRawSubscriptions },
          result: { id: subscriptionId },
        };
      }

      const derived = applyDerivedState(
        data,
        remainingTransactions,
        session,
        schemaVersion,
        existingTransactions,
      );
      const updatedRawTransactions = derived.transactions.map((effective) =>
        encryptTransaction(transactionFromApi(effective, schemaVersion), session),
      );
      return {
        updatedData: {
          ...derived.data,
          subscriptions: updatedRawSubscriptions,
          transactions: updatedRawTransactions,
        },
        result: { id: subscriptionId },
      };
    },
  );
}

/**
 * `POST /subscriptions/refresh` — generates whatever transactions are due
 * from active subscriptions and haven't already been generated
 * (`generateDueSubscriptionTransactions`, `packages/domain/src/transactions/
 * subscription-generation.ts`), then appends them in the same write every
 * other transaction mutation goes through (`applyDerivedState`), so Mojo/
 * Smile/Fire fund state and the Income accounting rebuild reflect the new
 * transactions atomically alongside them — an improvement over the original
 * app's per-transaction sequential persistence.
 */
async function refreshSubscriptions(deps, userId, { now = new Date() } = {}) {
  return withSubscriptionsWrite(
    deps,
    userId,
    ({ data, rawSubscriptions, session, schemaVersion, currency }) => {
      const subscriptions = decryptAllSubscriptions(rawSubscriptions, session, schemaVersion);
      const rawTransactions = data.transactions || [];
      const existingTransactions = toApiTransactions(
        rawTransactions,
        session,
        schemaVersion,
        currency,
      );
      const fundState = buildDerivedStateContext(data, session, schemaVersion).funds;
      const generation = generateDueSubscriptionTransactions(
        subscriptions,
        existingTransactions,
        fundState,
        now,
      );
      const result = {
        transactionsCreated: generation.transactionsCreated,
        subscriptionsProcessed: generation.subscriptionsProcessed,
      };
      if (generation.transactionsCreated === 0) {
        return { skipWrite: true, result };
      }

      const newTransactions = generation.transactions.map((transaction) => ({
        ...transaction,
        id: `tx_${crypto.randomUUID()}`,
        currency,
      }));
      const derived = applyDerivedState(
        data,
        [...existingTransactions, ...newTransactions],
        session,
        schemaVersion,
        existingTransactions,
      );
      const updatedRawTransactions = derived.transactions.map((effective) =>
        encryptTransaction(transactionFromApi(effective, schemaVersion), session),
      );
      return {
        updatedData: { ...derived.data, transactions: updatedRawTransactions },
        result,
      };
    },
  );
}

/**
 * `POST /subscriptions/batch` — bulk create/update/delete, mirroring
 * `transaction-repository.js`'s `batchTransactions` structurally (same
 * non-atomic-by-default/atomic-on-request outcome semantics). Deliberately
 * does NOT run `updateSubscription`/`deleteSubscription`'s stale-transaction
 * cleanup cascade (decision 1) — a bulk metadata edit shouldn't have the
 * side effect of silently deleting a caller's transactions across many
 * subscriptions at once; that stays a single-item, explicit-intent operation
 * via `PATCH`/`DELETE /subscriptions/{id}`.
 */
async function batchSubscriptions(deps, userId, items, { atomic = false } = {}) {
  return withSubscriptionsWrite(
    deps,
    userId,
    ({ data, rawSubscriptions, session, schemaVersion }) => {
      let working = decryptAllSubscriptions(rawSubscriptions, session, schemaVersion);
      let anyApplied = false;
      const outcomes = items.map((item) => {
        if (item.error) return { op: item.op, id: item.id, status: 'error', error: item.error };
        try {
          if (item.op === 'create') {
            assertLocationKnown(data, session, item.fields.locationId);
            const newSubscription = {
              id: `subscriptions_${crypto.randomUUID()}`,
              title: item.fields.title || '',
              account: item.fields.account,
              amountMinor: item.fields.amountMinor,
              startDate: item.fields.startDate,
              endDate: item.fields.endDate || null,
              category: item.fields.category,
              comment: item.fields.comment || '',
              frequency: item.fields.frequency || 'monthly',
              ...(item.fields.locationId ? { locationId: item.fields.locationId } : {}),
              ...(Array.isArray(item.fields.locationSplit)
                ? { locationSplit: item.fields.locationSplit }
                : {}),
            };
            normalizeSplitRule(newSubscription, data, session);
            working = [...working, newSubscription];
            anyApplied = true;
            return { op: 'create', status: 'created', id: newSubscription.id };
          }
          if (item.op === 'update') {
            const index = working.findIndex((subscription) => subscription.id === item.id);
            if (index === -1) throw new Error('No matching subscription exists.');
            assertNotPlanOwned(data, working[index], session);
            assertLocationKnown(data, session, item.fields.locationId, working[index].locationId);
            working = working.map((subscription, candidateIndex) => {
              if (candidateIndex !== index) return subscription;
              const { locationId: patched, ...rest } = item.fields;
              const next = { ...subscription, ...rest };
              if (patched !== undefined) {
                if (patched) next.locationId = patched;
                else delete next.locationId;
              }
              if (!next.locationId && item.fields.locationSplit === undefined) {
                delete next.locationSplit;
              }
              normalizeSplitRule(next, data, session, subscription.locationSplit);
              return next;
            });
            anyApplied = true;
            return { op: 'update', status: 'updated', id: item.id };
          }
          const target = working.find((subscription) => subscription.id === item.id);
          if (!target) {
            throw new Error('No matching subscription exists.');
          }
          assertNotPlanOwned(data, target, session);
          working = working.filter((subscription) => subscription.id !== item.id);
          anyApplied = true;
          return { op: 'delete', status: 'deleted', id: item.id };
        } catch (error) {
          return { op: item.op, id: item.id, status: 'error', error: error.message };
        }
      });

      const hasErrors = outcomes.some((outcome) => outcome.status === 'error');
      if ((atomic && hasErrors) || !anyApplied) {
        const results = outcomes.map((outcome) =>
          outcome.status === 'error' ? outcome : { ...outcome, status: 'not_applied' },
        );
        return { skipWrite: true, result: results };
      }

      return {
        updatedData: {
          ...data,
          subscriptions: working.map((subscription) =>
            encryptSubscription(subscription, session, schemaVersion),
          ),
        },
        result: outcomes.map((outcome) => {
          if (outcome.status === 'error' || outcome.op === 'delete') return outcome;
          const subscription = working.find((candidate) => candidate.id === outcome.id);
          return { ...outcome, subscription };
        }),
      };
    },
  );
}

