'use strict';

const { EncryptionSession } = require('@money/domain');
const {
  createLocation,
  deleteLocation,
  listLocations,
} = require('../../repositories/location-repository');
const { listTransfers, createTransfer } = require('../../repositories/transfer-repository');
const {
  createRecurringTransfer,
  deleteRecurringTransfer,
  getRecurringTransfer,
  listRecurringTransfers,
  refreshRecurringTransfers,
  updateRecurringTransfer,
} = require('../../repositories/recurring-transfer-repository');

const NOW = new Date('2026-04-15');

function harness(data = {}, encryptionConfig = { key: 'default', encryptDatabase: false }) {
  let document = { _id: 'user_1', _rev: '1-a', createdAt: 't', updatedAt: 't', data };
  const deps = {
    usersDb: {
      get: jest.fn(async () => structuredClone(document)),
      insert: jest.fn(async (next) => {
        document = { ...next, _rev: '2-b' };
      }),
    },
    authDb: { get: jest.fn(async () => ({ encryptionConfig })) },
  };
  return { deps, doc: () => document };
}

const baseData = () => ({ mojo: { amount: 0, target: 100000 }, smile: [], fire: [] });
const balances = async (deps) =>
  Object.fromEntries((await listLocations(deps, 'user_1')).map((l) => [l.name, l.amountMinor]));

async function setup(deps) {
  const main = await createLocation(deps, 'user_1', { name: 'Main', amountMinor: 100000 });
  const shared = await createLocation(deps, 'user_1', { name: 'Shared', amountMinor: 0 });
  const other = await createLocation(deps, 'user_1', { name: 'Other', amountMinor: 0 });
  return { main, shared, other };
}

const rule = (a, extra = {}) => ({
  title: 'Shared account',
  fromLocationId: a.main.id,
  toLocationId: a.shared.id,
  amountMinor: 5000,
  startDate: '2026-03-23',
  frequency: 'weekly',
  ...extra,
});

describe('recurring transfers', () => {
  it('creating a rule generates the due transfers and moves both balances in the same write', async () => {
    const { deps, doc } = harness(baseData());
    const a = await setup(deps);
    const created = await createRecurringTransfer(deps, 'user_1', rule(a), { now: NOW });
    expect(created.id).toMatch(/^rtransfer_/);
    expect(created.transfersCreated).toBe(4);
    // weekly from 23.03: 23.03, 30.03, 06.04, 13.04 = 4 x 50.00
    expect(await balances(deps)).toEqual({ Main: 80000, Shared: 20000, Other: 0 });
    const transfers = await listTransfers(deps, 'user_1');
    expect(transfers).toHaveLength(4);
    expect(transfers.every((t) => t.comment === 'Shared account')).toBe(true);
    expect((await getRecurringTransfer(deps, 'user_1', created.id)).amountMinor).toBe(5000);
    // stored decimal on a v1 document, rule and transfers
    expect(doc().data.recurringTransfers[0].amount).toBe(50);
  });

  it('is not a subscription or a transaction: nothing derived can see it', async () => {
    const { deps, doc } = harness(baseData());
    const a = await setup(deps);
    await createRecurringTransfer(deps, 'user_1', rule(a), { now: NOW });
    expect(doc().data.subscriptions).toBeUndefined();
    expect(doc().data.transactions).toBeUndefined();
    expect(doc().data.income).toBeUndefined();
  });

  it('refresh adds only what is new and never twice', async () => {
    const { deps } = harness(baseData());
    const a = await setup(deps);
    await createRecurringTransfer(deps, 'user_1', rule(a), { now: NOW });
    const same = await refreshRecurringTransfers(deps, 'user_1', { now: NOW });
    expect(same).toEqual({ transfersCreated: 0, rulesProcessed: 1 });
    const later = await refreshRecurringTransfers(deps, 'user_1', { now: new Date('2026-04-28') });
    expect(later.transfersCreated).toBe(2);
    expect(await balances(deps)).toEqual({ Main: 70000, Shared: 30000, Other: 0 });
  });

  it('a transfer deleted by hand is not what the rule recognises as generated by someone else', async () => {
    const { deps } = harness(baseData());
    const a = await setup(deps);
    await createTransfer(deps, 'user_1', {
      fromLocationId: a.main.id,
      toLocationId: a.shared.id,
      amountMinor: 5000,
      date: '2026-03-23',
      time: '09:00',
      comment: 'birthday gift',
    });
    const created = await createRecurringTransfer(deps, 'user_1', rule(a), { now: NOW });
    // the hand-made one looks alike but has another comment: the rule still makes its own 4
    expect(created.transfersCreated).toBe(4);
  });

  it('editing the amount changes the generated transfers in place and the balances follow', async () => {
    const { deps } = harness(baseData());
    const a = await setup(deps);
    const created = await createRecurringTransfer(deps, 'user_1', rule(a), { now: NOW });
    const ids = (await listTransfers(deps, 'user_1')).map((t) => t.id);
    await updateRecurringTransfer(deps, 'user_1', created.id, { amountMinor: 7500 }, { now: NOW });
    const after = await listTransfers(deps, 'user_1');
    expect(after.map((t) => t.id)).toEqual(ids);
    expect(after.every((t) => t.amountMinor === 7500)).toBe(true);
    expect(await balances(deps)).toEqual({ Main: 70000, Shared: 30000, Other: 0 });
  });

  it('moving the destination moves the generated transfers and both balances', async () => {
    const { deps } = harness(baseData());
    const a = await setup(deps);
    const created = await createRecurringTransfer(deps, 'user_1', rule(a), { now: NOW });
    await updateRecurringTransfer(
      deps,
      'user_1',
      created.id,
      { toLocationId: a.other.id },
      { now: NOW },
    );
    expect(await balances(deps)).toEqual({ Main: 80000, Shared: 0, Other: 20000 });
  });

  it('an end date in the past removes the transfers after it and gives that money back', async () => {
    const { deps } = harness(baseData());
    const a = await setup(deps);
    const created = await createRecurringTransfer(deps, 'user_1', rule(a), { now: NOW });
    await updateRecurringTransfer(
      deps,
      'user_1',
      created.id,
      { endDate: '2026-03-31' },
      { now: NOW },
    );
    expect((await listTransfers(deps, 'user_1')).map((t) => t.date)).toEqual([
      '2026-03-23',
      '2026-03-30',
    ]);
    expect(await balances(deps)).toEqual({ Main: 90000, Shared: 10000, Other: 0 });
  });

  it('deleting a rule keeps the transfers it made unless asked to remove them', async () => {
    const { deps } = harness(baseData());
    const a = await setup(deps);
    const first = await createRecurringTransfer(deps, 'user_1', rule(a), { now: NOW });
    expect(await deleteRecurringTransfer(deps, 'user_1', first.id, { now: NOW })).toEqual({
      id: first.id,
      transfersDeleted: 0,
    });
    expect(await listTransfers(deps, 'user_1')).toHaveLength(4);
    expect(await balances(deps)).toEqual({ Main: 80000, Shared: 20000, Other: 0 });

    const { deps: deps2 } = harness(baseData());
    const b = await setup(deps2);
    const second = await createRecurringTransfer(deps2, 'user_1', rule(b), { now: NOW });
    const result = await deleteRecurringTransfer(deps2, 'user_1', second.id, {
      deleteTransfers: true,
      now: NOW,
    });
    expect(result.transfersDeleted).toBe(4);
    expect(await listTransfers(deps2, 'user_1')).toEqual([]);
    expect(await balances(deps2)).toEqual({ Main: 100000, Shared: 0, Other: 0 });
    expect(await deleteRecurringTransfer(deps2, 'user_1', second.id)).toBeNull();
  });

  it('needs two different, existing locations and a sound schedule', async () => {
    const { deps } = harness(baseData());
    const a = await setup(deps);
    await expect(
      createRecurringTransfer(deps, 'user_1', rule(a, { toLocationId: a.main.id }), { now: NOW }),
    ).rejects.toMatchObject({ code: 'TRANSFER_INVALID' });
    await expect(
      createRecurringTransfer(deps, 'user_1', rule(a, { toLocationId: 'loc_nope' }), { now: NOW }),
    ).rejects.toMatchObject({ code: 'LOCATION_NOT_FOUND' });
    await expect(
      createRecurringTransfer(deps, 'user_1', rule(a, { frequency: 'daily' }), { now: NOW }),
    ).rejects.toMatchObject({ code: 'TRANSFER_INVALID' });
    await expect(
      createRecurringTransfer(deps, 'user_1', rule(a, { endDate: '2026-01-01' }), { now: NOW }),
    ).rejects.toMatchObject({ code: 'TRANSFER_INVALID' });
    expect(await listRecurringTransfers(deps, 'user_1')).toEqual([]);
  });

  it('deleting a location removes the rules that point at it but keeps the transfers they made', async () => {
    const { deps } = harness(baseData());
    const a = await setup(deps);
    await createRecurringTransfer(deps, 'user_1', rule(a), { now: NOW });
    await deleteLocation(deps, 'user_1', a.shared.id);
    expect(await listRecurringTransfers(deps, 'user_1')).toEqual([]);
    const kept = await listTransfers(deps, 'user_1');
    expect(kept).toHaveLength(4);
    expect(kept.every((t) => !('toLocationId' in t))).toBe(true);
  });

  it('works on an encrypted document and on a minor-unit (v2) document', async () => {
    const session = new EncryptionSession('secret');
    const enc = harness(
      {
        mojo: { amount: session.encrypt('0'), target: session.encrypt('100000') },
        smile: [],
        fire: [],
      },
      { key: 'secret', encryptDatabase: true },
    );
    const a = await setup(enc.deps);
    await createRecurringTransfer(enc.deps, 'user_1', rule(a), { now: NOW });
    const stored = enc.doc().data.recurringTransfers[0];
    expect(session.decrypt(stored.amount)).toBe('50');
    expect(session.decrypt(stored.fromLocationId)).toBe(a.main.id);
    expect(await balances(enc.deps)).toEqual({ Main: 80000, Shared: 20000, Other: 0 });

    const v2 = harness({ ...baseData(), meta: { schemaVersion: 2 } });
    const b = await setup(v2.deps);
    await createRecurringTransfer(v2.deps, 'user_1', rule(b), { now: NOW });
    expect(v2.doc().data.recurringTransfers[0].amount).toBe(5000);
    expect(await balances(v2.deps)).toEqual({ Main: 80000, Shared: 20000, Other: 0 });
  });
});
