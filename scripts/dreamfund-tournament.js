#!/usr/bin/env node
/**
 * The bot tournament of the Dreamfund (todo/dreamfund-multiplayer.md, slice 9): tables of bots only, played headless and rated with the
 * board's own Elo, until every strategy at every skill level has a rating at a difficulty. Run one difficulty per process (they take an
 * hour), then write the table the board starts its bots from:
 *
 *   node scripts/dreamfund-tournament.js --difficulty medium --tables 1300
 *   node scripts/dreamfund-tournament.js --write      (merges docs/dreamfund-balance/bot-ratings-*.json into the domain)
 *
 * Needs `npm run build:domain` first. Options: --seats 4, --rounds 40, --seed 1, --k 24, --dist <domain dist>.
 */
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const arg = (name, fallback) => {
  const at = process.argv.indexOf(`--${name}`);
  return at >= 0 ? process.argv[at + 1] : fallback;
};
const dist = path.resolve(root, arg('dist', 'packages/domain/dist/cashflow-game/dreamfund'));
const outDir = path.join(root, 'docs/dreamfund-balance');
const LEVELS = ['easy', 'medium', 'hard'];

if (process.argv.includes('--write')) {
  const ratings = {};
  for (const level of LEVELS) {
    const file = path.join(outDir, `bot-ratings-${level}.json`);
    if (!fs.existsSync(file)) continue;
    const { bots } = JSON.parse(fs.readFileSync(file, 'utf8'));
    // the best master is 1500, as everywhere on the board
    const best = Math.max(...bots.filter((b) => !b.botId.includes('--')).map((b) => b.rating));
    ratings[level] = Object.fromEntries(
      bots.map((b) => [b.botId, Math.max(100, Math.round(1500 + b.rating - best))]),
    );
  }
  const target = path.join(
    root,
    'packages/domain/src/cashflow-game/dreamfund/table/bot-ratings.generated.ts',
  );
  fs.writeFileSync(
    target,
    `// Generated by scripts/dreamfund-tournament.js --write from the bot tournaments. Do not edit.\n` +
      `import type { DreamfundLevel } from '../../analysis/dreamfund-benchmarks';\n\n` +
      `export const DREAM_BOT_RATINGS: Partial<Record<DreamfundLevel, Record<string, number>>> = ${JSON.stringify(ratings, null, 2)};\n`,
  );
  console.log(`written ${path.relative(root, target)} for ${Object.keys(ratings).join(', ')}`);
  process.exit(0);
}

const { runBotTournament } = require(path.join(dist, 'table/tournament.js'));
const difficulty = arg('difficulty', 'medium');
if (!LEVELS.includes(difficulty)) throw new Error(`difficulty is one of ${LEVELS.join(', ')}`);
const tables = Number(arg('tables', 1300));
const started = Date.now();
const bots = runBotTournament({
  difficulty,
  tables,
  seats: Number(arg('seats', 4)),
  roundLimit: Number(arg('rounds', 40)),
  seed: Number(arg('seed', 1)),
  k: Number(arg('k', 24)),
});
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(
  path.join(outDir, `bot-ratings-${difficulty}.json`),
  JSON.stringify({ difficulty, tables, bots }, null, 1),
);
for (const b of bots.slice(0, 12)) {
  console.log(
    `${b.botId.padEnd(22)} ${Math.round(b.rating)}  ${b.games} games, ${b.tableWins} wins`,
  );
}
console.log(
  `${difficulty}: ${tables} tables in ${((Date.now() - started) / 60000).toFixed(1)} min`,
);
