const DICTIONARIES: Record<TablesLang, TablesTexts> = { en, de, es, fr, cn, ar };

/** The words for a language code as the app names it (`zh`/`zh-CN` count as cn); English when unknown. */
export function tablesTexts(lang: string | undefined | null): TablesTexts {
  const code = (lang ?? 'en').toLowerCase().slice(0, 2);
  const key = (code === 'zh' ? 'cn' : code) as TablesLang;
  return DICTIONARIES[key] ?? en;
}
