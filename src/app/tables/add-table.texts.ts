const DICTIONARIES: Record<TablesLang, AddTableTexts> = { en, de, es, fr, cn, ar };

export function addTableTexts(lang: string | undefined | null): AddTableTexts {
  const code = String(lang ?? 'en')
    .toLowerCase()
    .slice(0, 2);
  return DICTIONARIES[(code === 'zh' ? 'cn' : code) as TablesLang] ?? en;
}
