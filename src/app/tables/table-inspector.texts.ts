const DICTIONARIES: Record<TablesLang, TableInspectorTexts> = { en, de, es, fr, cn, ar };

export function tableInspectorTexts(lang: string | undefined | null): TableInspectorTexts {
  const code = (lang ?? 'en').toLowerCase().slice(0, 2);
  const key = (code === 'zh' ? 'cn' : code) as TablesLang;
  return DICTIONARIES[key] ?? en;
}
