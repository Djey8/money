const DICTIONARIES: Record<TablesLang, HallTexts> = { en, de, es, fr, cn, ar };

export function hallTexts(lang: string | undefined | null): HallTexts {
  const code = String(lang ?? 'en')
    .toLowerCase()
    .slice(0, 2);
  return DICTIONARIES[(code === 'zh' ? 'cn' : code) as TablesLang] ?? en;
}
