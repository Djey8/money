const DICTIONARIES: Record<LeaderboardLang, LeaderboardTexts> = { en, de, es, fr, cn, ar };

export function leaderboardTexts(lang: string | undefined | null): LeaderboardTexts {
  const code = (lang ?? 'en').toLowerCase().slice(0, 2);
  const key = (code === 'zh' ? 'cn' : code) as LeaderboardLang;
  return DICTIONARIES[key] ?? en;
}
