const DICTIONARIES: Record<TablesLang, TableCardsTexts> = { en, de, es, fr, cn, ar };

export function tableCardsTexts(lang: string | undefined | null): TableCardsTexts {
  const code = (lang ?? 'en').toLowerCase().slice(0, 2);
  const key = (code === 'zh' ? 'cn' : code) as TablesLang;
  return DICTIONARIES[key] ?? en;
}
