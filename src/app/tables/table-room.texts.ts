const DICTIONARIES: Record<TablesLang, TableRoomTexts> = { en, de, es, fr, cn, ar };

export function tableRoomTexts(lang: string | undefined | null): TableRoomTexts {
  const code = (lang ?? 'en').toLowerCase().slice(0, 2);
  const key = (code === 'zh' ? 'cn' : code) as TablesLang;
  return DICTIONARIES[key] ?? en;
}
